#!/usr/bin/env bash
# =============================================================================
# Fleet frontend: fetch the runtime config from AWS SSM into an nginx snippet
# (set $fleet_* ...) that the vhost includes and injects into index.html.
#
# Run by fleet-app-frontend-runtime-fetch.service (root oneshot) at boot and on
# every deploy. Reads /fleet-frontend/prod/* (eu-west-1) with the EC2 instance
# role. This config is PUBLIC (served to the browser): SSM String only, never a
# secret. §3.10: runs as root, installed in /usr/local/sbin from root's mirror.
#
# Each value ends up inside "..." twice: an nginx `set` string and a JS string
# literal inside <script>. Values that could break out of either are refused
# (nothing is written, the unit fails, the deploy goes red).
# =============================================================================
set -euo pipefail

SSM_PREFIX="${FLEET_FRONTEND_SSM_PREFIX:-/fleet-frontend/prod}"
AWS_REGION="${AWS_REGION:-eu-west-1}"
OUT_FILE="${FLEET_FRONTEND_RUNTIME_FILE:-/etc/nginx/snippets/fleet-frontend-runtime.conf}"

echo "[frontend-runtime] prefix=$SSM_PREFIX region=$AWS_REGION out=$OUT_FILE"

RAW_FILE="$(mktemp)"
TMP_FILE="$(mktemp)"
BAK_FILE="$(mktemp)"
trap 'rm -f "$RAW_FILE" "$TMP_FILE" "$BAK_FILE"' EXIT

aws ssm get-parameters-by-path \
    --path "$SSM_PREFIX" \
    --recursive \
    --region "$AWS_REGION" \
    --output json > "$RAW_FILE"

python3 - "$SSM_PREFIX" "$TMP_FILE" "$RAW_FILE" <<'PY'
import json
import re
import sys

prefix, out_path, raw_path = sys.argv[1:4]
with open(raw_path, encoding="utf-8") as fh:
    params = json.load(fh).get("Parameters", [])

values = {
    "API_BASE_URL": "",
    "SENTRY_DSN": "",
    "SENTRY_ENV": "production",
    "SENTRY_RELEASE": "",
}

# " \ ' end or escape the JS / nginx strings, $ is nginx interpolation, ; ends an
# nginx directive, < > could close the <script>, control chars incl. CR/LF.
FORBIDDEN = re.compile(r'["\\$;\'<>\x00-\x1f\x7f\r\n]')


def fail(msg):
    sys.stderr.write(f"ERROR: {msg}; refusing, nothing written.\n")
    sys.exit(1)


for p in params:
    key = p["Name"][len(prefix):].lstrip("/")
    if key not in values:
        continue
    value = p["Value"]
    if FORBIDDEN.search(value):
        fail(f"value for {key} contains a forbidden character")
    values[key] = value.strip()

# runtime-config.ts refuses anything but an absolute URL: an https origin here.
if not re.fullmatch(r"https://[A-Za-z0-9.-]+(:[0-9]{1,5})?/?", values["API_BASE_URL"]):
    fail("API_BASE_URL must be an https origin such as https://fleet-api.foxugly.com")

# Sentry DSN https://<key>@<host>/<project> -> CSP report-uri
# https://<host>/api/<project>/security/?sentry_key=<key>. No DSN: no report.
csp_report = ""
dsn = values["SENTRY_DSN"]
if dsn:
    m = re.fullmatch(r"https://([0-9a-f]+)@([A-Za-z0-9.-]+\.sentry\.io)/([0-9]+)", dsn)
    if not m:
        fail("SENTRY_DSN is not a https://<key>@<host>.sentry.io/<project> DSN")
    key, host, project = m.groups()
    csp_report = f"; report-uri https://{host}/api/{project}/security/?sentry_key={key}"

lines = [
    "# AUTO-GENERATED by deploy/fetch-frontend-runtime-from-ssm.sh; source of truth SSM.",
    f'set $fleet_api_base       "{values["API_BASE_URL"]}";',
    f'set $fleet_sentry_dsn     "{values["SENTRY_DSN"]}";',
    f'set $fleet_sentry_env     "{values["SENTRY_ENV"]}";',
    f'set $fleet_sentry_release "{values["SENTRY_RELEASE"]}";',
    f'set $fleet_csp_report     "{csp_report}";',
]
with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines) + "\n")
PY

if [ -f "$OUT_FILE" ] && cmp -s "$TMP_FILE" "$OUT_FILE"; then
    echo "[frontend-runtime] $OUT_FILE unchanged: no reload needed"
    exit 0
fi

had_previous=0
if [ -f "$OUT_FILE" ]; then
    cp -p "$OUT_FILE" "$BAK_FILE"
    had_previous=1
fi
mkdir -p "$(dirname "$OUT_FILE")"
install -m 0644 -o root -g root "$TMP_FILE" "$OUT_FILE"
echo "[frontend-runtime] $OUT_FILE updated"

# A snippet nginx rejects must not stay on disk: it would block every later
# reload on the box, for every site.
if ! nginx -t; then
    if [ "$had_previous" = 1 ]; then
        install -m 0644 -o root -g root "$BAK_FILE" "$OUT_FILE"
    else
        rm -f "$OUT_FILE"
    fi
    echo "ERROR: nginx -t failed after writing $OUT_FILE; previous state restored, no reload" >&2
    exit 3
fi
systemctl reload nginx
echo "[frontend-runtime] nginx reloaded"
